"""Object storage behind one small interface.

- LocalStorage: files on disk (development, tests). Downloads stream through the API.
- S3Storage: any S3-compatible API. Production uses a *private* Backblaze B2 bucket; downloads
  use 60-second presigned URLs issued only after the API has authorized the request.

Keys are generated by the server (`ws/<workspace>/docs/<document>/<uuid>`) and never contain
user-supplied filenames, so path traversal and PII-in-keys are impossible by construction.
"""

import asyncio
import os
import re
import shutil
import uuid
from functools import lru_cache
from pathlib import Path
from typing import Protocol
from urllib.parse import quote, urlsplit

from app.core.config import get_settings


class StorageError(Exception):
    pass


class Storage(Protocol):
    async def put_file(self, key: str, source: Path, content_type: str) -> None: ...
    async def download_to(self, key: str, dest: Path) -> None: ...
    async def delete(self, key: str) -> None: ...
    async def delete_prefix(self, prefix: str) -> None: ...
    async def presigned_download_url(
        self, key: str, filename: str, content_type: str
    ) -> str | None:
        """None means "not supported - stream through the API instead"."""
        ...


def document_key(workspace_id: uuid.UUID, document_id: uuid.UUID) -> str:
    return f"ws/{workspace_id}/docs/{document_id}/{uuid.uuid4().hex}"


def content_disposition(filename: str) -> str:
    # RFC 6266/5987: ASCII fallback + UTF-8 name; always "attachment" so the browser never
    # renders an uploaded file inline in our origin.
    ascii_name = filename.encode("ascii", "ignore").decode().replace('"', "") or "document"
    return f"attachment; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(filename)}"


class LocalStorage:
    def __init__(self, root: str) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):  # defense in depth; keys are server-generated
            raise StorageError("Invalid storage key")
        return path

    async def put_file(self, key: str, source: Path, content_type: str) -> None:
        dest = self._path(key)

        def _copy() -> None:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, dest)

        await asyncio.to_thread(_copy)

    async def download_to(self, key: str, dest: Path) -> None:
        src = self._path(key)
        if not src.exists():
            raise StorageError("Object not found")
        await asyncio.to_thread(shutil.copyfile, src, dest)

    def local_path(self, key: str) -> Path:
        return self._path(key)

    async def delete(self, key: str) -> None:
        path = self._path(key)

        def _rm() -> None:
            path.unlink(missing_ok=True)
            # Tidy empty parent folders up to the root.
            for parent in path.parents:
                if parent == self.root or not parent.is_relative_to(self.root):
                    break
                try:
                    parent.rmdir()
                except OSError:
                    break

        await asyncio.to_thread(_rm)

    async def delete_prefix(self, prefix: str) -> None:
        path = self._path(prefix)
        if path != self.root:
            await asyncio.to_thread(shutil.rmtree, path, True)

    async def presigned_download_url(
        self, key: str, filename: str, content_type: str
    ) -> str | None:
        return None


_B2_HOST = re.compile(r"^s3\.([a-z0-9-]+)\.backblazeb2\.com$")


def s3_region_for(endpoint_url: str | None, configured: str) -> str:
    """Backblaze B2 signs requests with the region in its endpoint (s3.<region>.backblazeb2.com),
    so with the default "auto" (right for Cloudflare R2) we read it from the endpoint."""
    if configured != "auto" or not endpoint_url:
        return configured
    match = _B2_HOST.match(urlsplit(endpoint_url).hostname or "")
    return match.group(1) if match else configured


class S3Storage:
    def __init__(self) -> None:
        import boto3
        from botocore.config import Config

        s = get_settings()
        if not (s.s3_bucket and s.s3_access_key_id and s.s3_secret_access_key):
            raise StorageError(
                "S3 storage needs S3_BUCKET, S3_ACCESS_KEY_ID and S3_SECRET_ACCESS_KEY"
            )
        self.bucket = s.s3_bucket
        self.ttl = s.download_url_ttl_seconds
        self.client = boto3.client(
            "s3",
            endpoint_url=s.s3_endpoint_url,
            aws_access_key_id=s.s3_access_key_id.get_secret_value(),
            aws_secret_access_key=s.s3_secret_access_key.get_secret_value(),
            region_name=s3_region_for(s.s3_endpoint_url, s.s3_region),
            config=Config(
                signature_version="s3v4",
                retries={"max_attempts": 3, "mode": "standard"},
                # boto3 >= 1.36 adds CRC checksum headers to every upload by default. Not every
                # S3-compatible service (B2, R2, MinIO versions) accepts them; send only when required.
                request_checksum_calculation="when_required",
                response_checksum_validation="when_required",
            ),
        )

    async def put_file(self, key: str, source: Path, content_type: str) -> None:
        await asyncio.to_thread(
            self.client.upload_file,
            str(source),
            self.bucket,
            key,
            ExtraArgs={"ContentType": content_type},
        )

    async def download_to(self, key: str, dest: Path) -> None:
        try:
            await asyncio.to_thread(self.client.download_file, self.bucket, key, str(dest))
        except Exception as exc:
            raise StorageError("Could not read the stored file") from exc

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self.client.delete_object, Bucket=self.bucket, Key=key)

    async def delete_prefix(self, prefix: str) -> None:
        def _delete_all() -> None:
            paginator = self.client.get_paginator("list_objects_v2")
            for page in paginator.paginate(Bucket=self.bucket, Prefix=prefix):
                keys = [{"Key": o["Key"]} for o in page.get("Contents", [])]
                if keys:
                    self.client.delete_objects(
                        Bucket=self.bucket, Delete={"Objects": keys, "Quiet": True}
                    )

        await asyncio.to_thread(_delete_all)

    async def presigned_download_url(
        self, key: str, filename: str, content_type: str
    ) -> str | None:
        return await asyncio.to_thread(
            self.client.generate_presigned_url,
            "get_object",
            Params={
                "Bucket": self.bucket,
                "Key": key,
                "ResponseContentDisposition": content_disposition(filename),
                "ResponseContentType": content_type,
            },
            ExpiresIn=self.ttl,
        )


@lru_cache
def get_storage() -> Storage:
    s = get_settings()
    if s.storage_backend == "s3":
        return S3Storage()
    os.makedirs(s.storage_local_dir, exist_ok=True)
    return LocalStorage(s.storage_local_dir)
